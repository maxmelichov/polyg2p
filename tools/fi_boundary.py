"""Finnish boundary gemination (rajageminaatio): build the infinitive lists and
measure trigger detection against Wiktionary.

WikiPron's `fin_latn_broad.tsv` marks a word that lengthens the next word's
initial consonant with a final `ˣ` (`tehdä` -> `t e h d æˣ`).

  fi_boundary.py build   # writes src/fi_verbs.rs from the gold + wordfreq
  fi_boundary.py eval    # precision / recall of the engine's triggers vs `ˣ`

`build` keeps first infinitives the suffix rules in src/fi.rs cannot see:
gold entries that always carry `ˣ`, with a wordfreq Zipf frequency of 3.0 or
more, in three shapes (vowel + a/ä: sanoa, lukea; -lla/-llä: ajatella; -aa/-ää:
antaa; -sta/-stä: nousta). A shape that is also an inflected form of another
word (antaa = 3rd person singular, oppia = partitive of oppi, ilmaista =
partitive of ilmainen) goes to the list that needs an infinitive context.
"""
import collections, os, re, subprocess, sys, unicodedata
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
SRC = os.environ.get("POLYG2P_SRC", os.path.join(HERE, "..", "sources"))
CLI = os.environ.get("G2P_CLI", os.path.join(HERE, "..", "target", "release", "g2p"))
ZIPF = 3.0
NUC = r"aa|ee|ii|oo|uu|yy|ää|öö|ai|ei|oi|ui|yi|äi|öi|au|eu|iu|ou|ey|iy|äy|öy|ie|uo|yö|[aeiouyäö]"
# -aa/-ää verbs the gold lists with and without ˣ because a noun form is spelled the same
EXTRA_CTX = """tarkoittaa riittää johtaa kantaa tuottaa vähentää siirtää äänestää luottaa jaksaa syyttää edustaa
menettää todistaa toimittaa luovuttaa laajentaa asentaa kuluttaa rahoittaa maksaa laulaa muistaa kaivaa jauhaa""".split()
# imperative / connegative forms, not infinitives
NOT_INF = {"kestä", "estä"}


def gold():
    g = collections.defaultdict(set)
    for line in open(os.path.join(SRC, "fin_latn_broad.tsv"), encoding="utf8"):
        w, p = line.rstrip("\n").split("\t")
        g[unicodedata.normalize("NFC", w)].add(p.replace(" ", ""))
    st = {}
    for w, ps in g.items():
        if re.fullmatch(r"[a-zäöå]+", w) and len(w) > 1:
            a = [p.endswith("ˣ") for p in ps]
            st[w] = "X" if all(a) else "x?" if any(a) else "0"
    return st


def syl(w):
    return len(re.findall(NUC, w))


def build():
    from wordfreq import zipf_frequency
    st = gold()
    X = [w for w, s in st.items() if s == "X" and zipf_frequency(w, "fi") >= ZIPF and w not in NOT_INF]
    hiatus = [w for w in X if re.search(r"(oa|ua|ea|ia|yä|eä|iä|öä)$", w) and syl(w) >= 2]
    lla = [w for w in X if re.search(r"[aeiouyäö]ll[aä]$", w) and syl(w) >= 3]
    aa = [w for w in X if re.search(r"(aa|ää)$", w) and syl(w) >= 2 and (w[:-1] + "t" + w[-1]) not in st]
    sta = [w for w in X if re.search(r"st[aä]$", w)]
    always = sorted({w for w in hiatus if w[:-1] not in st} | set(lla))
    ctx = sorted({w for w in hiatus if w[:-1] in st} | set(aa) | set(sta) | set(EXTRA_CTX))

    def arr(name, doc, words):
        rows, line = [], "   "
        for w in words:
            if len(line) + len(w) + 4 > 112:
                rows.append(line)
                line = "   "
            line += f' "{w}",'
        rows.append(line)
        return f"{doc}\npub const {name}: &[&str] = &[\n" + "\n".join(rows) + "\n];\n"

    out = ("//! Finnish first infinitives for boundary gemination, generated by\n"
           "//! `tools/fi_boundary.py build` from Wiktionary (WikiPron `fin_latn_broad.tsv`,\n"
           f"//! entries that always carry the final `ˣ`) and wordfreq (Zipf >= {ZIPF}). Sorted;\n"
           "//! looked up by binary search. Do not edit by hand.\n\n"
           + arr("INFINITIVE", "/// Infinitives no other word form is spelled like (sanoa, ajatella).", always) + "\n"
           + arr("INFINITIVE_CTX", "/// Infinitives spelled like a finite or noun form (antaa, oppia, ilmaista):\n"
                 "/// they geminate only where the clause calls for an infinitive.", ctx))
    open(os.path.join(HERE, "..", "src", "fi_verbs.rs"), "w", encoding="utf8").write(out)
    print(f"INFINITIVE {len(always)}, INFINITIVE_CTX {len(ctx)}")


def run(xs):
    return subprocess.run([CLI, "fi"], input="\n".join(xs) + "\n", capture_output=True, text=True, check=True).stdout.split("\n")[:len(xs)]


def evaluate(show):
    from wordfreq import word_frequency
    st = gold()
    words = sorted(st)
    # "voin W sen": W after an infinitive-governing verb, the next word starts with s;
    # "hän W sen": W as a finite form would stand
    for name, frame in [("after `voin` (infinitive context)", "voin {} {}"), ("after `hän` (finite context)", "hän {} {}")]:
        a = run([frame.format(w, "sen") for w in words])
        # the mark goes on the first consonant of the word after (`sːˈen`); `sen` has no other ː
        trig = ["ː" in x.split(" ")[-1] for x in a]
        tab, mass, ex = collections.Counter(), collections.Counter(), collections.defaultdict(list)
        for w, t in zip(words, trig):
            f = word_frequency(w, "fi")
            tab[(st[w], t)] += 1
            mass[(st[w], t)] += f
            ex[(st[w], t)].append((f, w))
        p = mass[("X", True)] / max(1e-12, mass[("X", True)] + mass[("0", True)])
        r = mass[("X", True)] / max(1e-12, mass[("X", True)] + mass[("X", False)])
        print(f"{name}: {len(words)} gold words")
        print("   types  " + "  ".join(f"{k[0]}/{'gem' if k[1] else 'no'}={v}" for k, v in sorted(tab.items())))
        print(f"   frequency-weighted: precision {p:.1%} (always-ˣ vs never-ˣ words we geminate after), recall {r:.1%} of always-ˣ words")
        if show:
            for k in [("0", True), ("X", False)]:
                print("  ", k, " ".join(w for _, w in sorted(ex[k], reverse=True)[:show]))


if __name__ == "__main__":
    if sys.argv[1:2] == ["build"]:
        build()
    else:
        evaluate(int(sys.argv[2]) if len(sys.argv) > 2 else 0)
