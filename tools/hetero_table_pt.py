#!/usr/bin/env python3
"""Writes data/hetero_pt.tsv: Brazilian Portuguese noun/verb pairs whose stressed e/o is closed in the noun and
open in the 1st person singular of the verb (jogo, almoço, ...), colher the other way round.
Both vowel qualities of every word must be attested as pronunciations of that word in WikiPron's por_latn_bz_broad
(CC BY-SA, downloaded for this check only, not stored in the repo); a word without both is dropped."""
import subprocess, sys, re

WIKIPRON = sys.argv[1]
BIN = sys.argv[2] if len(sys.argv) > 2 else "target/release/g2p"
# word: (noun vowel, verb vowel)
PAIRS = {w: ("c", "o") for w in """jogo almoço governo acordo apoio choro olho esforço reforço troco sopro gosto começo tempero selo gelo
conserto concerto acerto aperto emprego endereço retorno contorno transtorno desespero namoro""".split()}
# words kept on the rules: the gate (50+ human-gold decisions with the model below the rules) and the evidence floor
# (a word needs 30 training decisions in each class, or 15+ gold decisions with the model 10 points above the rules);
# the list is tools/hetero_rule_pt.txt
RULE_MODE = set(open(__import__("os").path.join(__import__("os").path.dirname(__import__("os").path.abspath(__file__)), "hetero_rule_pt.txt")).read().split())
VOW = {"o": ("o", "ɔ"), "e": ("e", "ɛ")}
att = {}
for line in open(WIKIPRON, encoding="utf8"):
    w, p = line.rstrip("\n").split("\t")
    att.setdefault(w, set()).add(p.replace(" ", ""))
rows = ["# Brazilian Portuguese heteronyms: noun (closed e/o) vs 1sg verb (open ɛ/ɔ); colher reversed. Generated by tools/hetero_table_pt.py;",
        "# both vowel qualities attested as pronunciations of the word in WikiPron before a word is listed.",
        "# word\tk\treading\ttag\tnote\tmode"]
kept, dropped = [], []
words = list(PAIRS) + ["colher"]
ph = subprocess.run([BIN, "pt", "--words"], input="\n".join(words) + "\n", capture_output=True, text=True).stdout.split("\n")
for w, rule in zip(words, ph):
    m = re.search(r"ˈ([eɛoɔ])", rule)
    if not m:
        dropped.append((w, "no stressed e/o in " + rule))
        continue
    base = "e" if m.group(1) in "eɛ" else "o"
    closed, opened = VOW[base]
    a = att.get(w, set())
    if not (any(closed in x for x in a) and any(opened in x for x in a)):
        dropped.append((w, "not both attested"))
        continue
    sub = lambda v: rule[:m.start(1)] + v + rule[m.end(1):]
    if w == "colher":
        n, v = sub(opened), sub(closed)
    else:
        n, v = sub(closed), sub(opened)
    mode = "rule" if w in RULE_MODE else ""
    rows.append(f"{w}\t0\tph:{n}\tNOUN\tnoun\t{mode}")
    rows.append(f"{w}\t1\tph:{v}\tVERB\tverb\t{mode}")
    kept.append(w)
open("data/hetero_pt.tsv", "w", encoding="utf8").write("\n".join(rows) + "\n")
print("kept", len(kept), kept)
print("dropped", dropped)
